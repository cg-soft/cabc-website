// Development only. Copy the selected unmodified assets from an extracted
// pdfjs-dist@6.5.438 npm tarball, retaining its licenses and an exact allowlist.
import { readFileSync, readdirSync, mkdirSync, copyFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const source = path.resolve(process.argv[2] || ".");
const version = "6.5.438";
if (JSON.parse(readFileSync(path.join(source, "package.json"))).version !== version)
  throw new Error(`Expected extracted pdfjs-dist@${version}.`);
const prefix = `vendor/pdfjs-${version}`;
const files = ["LICENSE", "legacy/build/pdf.min.mjs", "legacy/build/pdf.worker.min.mjs",
  ...readdirSync(path.join(source, "cmaps")).filter(name => name.endsWith(".bcmap") || name.startsWith("LICENSE")).map(name => `cmaps/${name}`),
  ...readdirSync(path.join(source, "standard_fonts")).filter(name => /\.(pfb|ttf)$/.test(name) || name.startsWith("LICENSE")).map(name => `standard_fonts/${name}`),
  "wasm/jbig2_nowasm_fallback.js", "wasm/openjpeg_nowasm_fallback.js",
  "wasm/LICENSE_JBIG2", "wasm/LICENSE_OPENJPEG", "wasm/LICENSE_PDFJS_JBIG2", "wasm/LICENSE_PDFJS_OPENJPEG"];
const targets = [];
for (const file of files) {
  const relative = `${prefix}/${file.replace("legacy/build/", "")}`;
  const target = path.join(root, "public", relative);
  mkdirSync(path.dirname(target), { recursive: true });
  copyFileSync(path.join(source, file), target);
  targets.push(`/${relative}`);
}
writeFileSync(path.join(root, "pdf-assets.mjs"),
  `// Generated by scripts/vendor-pdfjs.mjs; exact public PDF.js asset allowlist.\nexport const PDF_ASSETS = new Set(${JSON.stringify(targets.sort(), null, 2)});\n`);
console.log(`Vendored PDF.js ${version}: ${targets.length} files.`);
