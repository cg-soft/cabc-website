import { createHash } from "node:crypto";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = path.dirname(fileURLToPath(import.meta.url));
export const VERSION_PATTERN = /const FRONTEND_VERSION = "[^"\r\n]+";/g;

// Hash runtime inputs, not deployment config, tests, docs or generated metadata.
export function releaseFingerprint(root = ROOT) {
  const files = readdirSync(root).filter(name =>
    !name.endsWith("-tests.mjs") && name !== "tests.mjs" && name !== "release.mjs" &&
    (/\.(mjs|cjs|sql)$/.test(name) || ["package.json", "package-lock.json"].includes(name)));
  function walk(dir) {
    for (const entry of readdirSync(path.join(root, dir), { withFileTypes: true })) {
      const name = `${dir}/${entry.name}`;
      if (entry.isDirectory()) walk(name);
      else if (entry.isFile() && name !== "public/config.js") files.push(name);
    }
  }
  walk("public");
  const hash = createHash("sha256");
  for (const name of files.sort()) {
    let bytes = readFileSync(path.join(root, name));
    if (name === "public/app.js") {
      const text = bytes.toString();
      if ([...text.matchAll(VERSION_PATTERN)].length !== 1)
        throw new Error("Expected one embedded frontend version marker.");
      bytes = Buffer.from(text.replace(VERSION_PATTERN, 'const FRONTEND_VERSION = "STAMP";'));
    }
    hash.update(name); hash.update("\0"); hash.update(String(bytes.length));
    hash.update("\0"); hash.update(bytes); hash.update("\0");
  }
  return hash.digest("hex");
}

export function stampRelease(root = ROOT) {
  const base = JSON.parse(readFileSync(path.join(root, "package.json"), "utf8")).version;
  if (!/^\d+\.\d+\.\d+$/.test(base)) throw new Error("Use a numeric major.minor.patch package version.");
  const fingerprint = releaseFingerprint(root);
  const version = `${base}+${fingerprint.slice(0, 12)}`;
  const app = path.join(root, "public/app.js");
  writeFileSync(app, readFileSync(app, "utf8").replace(VERSION_PATTERN, `const FRONTEND_VERSION = "${version}";`));
  writeFileSync(path.join(root, "release.mjs"),
    `// Generated by npm run release:version. Do not edit manually.\nexport const VERSION = "${version}";\nexport const SOURCE_FINGERPRINT = "${fingerprint}";\n`);
  return version;
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href)
  console.log(stampRelease());
